import Foundation

assert(DemoBrand.isWhatsApp)
assert(SampleData.sessions.count == 8)
let ids = Set(SampleData.sessions.map(\.id))
assert(ids.count == 8 && ids.allSatisfy { $0.hasPrefix("wa-") })
assert(Set(PrototypeState.seedHistory) == ids)
assert(PrototypeState().history.current == "wa-maya")
assert(PrototypeState().conversations["wa-maya"]?.draft == "Let’s meet at ")
assert(SampleData.session("wa-alex").activity == .working)
assert(SampleData.session("wa-design").activity == .newReply)
assert(SessionActivity.working.label == "Typing")
assert(SampleData.sessions.allSatisfy { !$0.messages.isEmpty })
assert(WhatsAppData.chats.contains { $0.group } && WhatsAppData.chats.contains { !$0.group })
assert(SwipeDecision.historyStep(forTranslation: 100) == -1)
assert(SwipeDecision.historyStep(forTranslation: -100) == 1)
var state = PrototypeState()
state.history.move(-1)
state.conversations["wa-design"] = .init(draft: "Keep this reply", readingPosition: 130, sentMessages: ["Only on this device"])
state.settings.cardScale = 0.65
let url = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString).appendingPathComponent("state.json")
let store = PrototypeStore(url: url)
try store.save(state)
assert(store.load() == state)
assert(store.load()?.conversations["wa-maya"]?.draft == "Let’s meet at ")
assert(store.load()?.history.current == "wa-design")
try FileManager.default.removeItem(at: url.deletingLastPathComponent())
print("WhatsApp sample history, activity, direction and independent draft/message state checks passed.")
